def get_provider(name: str) -> Optional[ProviderMetadata]:
    """Retrieves metadata for a named provider."""
    return PROVIDER_REGISTRY.get(name)


def list_providers() -> List[ProviderMetadata]:
    """Returns a list of all registered providers."""
    return list(PROVIDER_REGISTRY.values())


def get_providers_by_category(category: ProviderCategory) -> List[ProviderMetadata]:
    """Filters providers by their structural category."""
    return [p for p in PROVIDER_REGISTRY.values() if p.category == category]
